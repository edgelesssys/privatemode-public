// Package usage provides types for tracking inference usage statistics.
package usage

// Stats contains the statistics of resources consumed while processing an inference request.
type Stats struct {
	// PromptTokens is the number of input tokens processed by the model, excluding tokens served
	// from the prompt cache.
	PromptTokens int64 `json:"prompt_tokens"`
	// CachedPromptTokens is the number of input tokens served from the prompt cache.
	CachedPromptTokens int64 `json:"cached_prompt_tokens"`
	// CompletionTokens is the number of output tokens generated by the model.
	CompletionTokens int64 `json:"completion_tokens"`
	// AudioSeconds is the duration, in seconds, of audio input processed by the model.
	AudioSeconds int64 `json:"audio_seconds"`
}

// Add the values of another [Stats] and return the result.
func (s Stats) Add(other Stats) Stats {
	return Stats{
		PromptTokens:       s.PromptTokens + other.PromptTokens,
		CachedPromptTokens: s.CachedPromptTokens + other.CachedPromptTokens,
		CompletionTokens:   s.CompletionTokens + other.CompletionTokens,
		AudioSeconds:       s.AudioSeconds + other.AudioSeconds,
	}
}
